# =============================================================================
# build_msi.ps1 - the Windows Installer package (deploy\tmDataQualityAnalyzer.wxs) from the staged application.
#
# build_package.ps1 stages the signed application in <Stage>\app and the full manual in <Stage>\manual, then calls this to
# turn them into tmDataQualityAnalyzer-vX.Y.Z_setup.msi. It can also be run by hand against an existing staging folder.
#
# WiX is a repo-local dotnet tool pinned in dotnet-tools.json (6.0.2); its UI extension is fetched into the repository's
# .wix\ cache (gitignored) on first use, at the same version. Nothing is installed globally.
#
# Parameters:
#   -Version        X.Y.Z, the MSI ProductVersion (AppVersion; a pre-release suffix is not a valid MSI version).
#   -Stage          the package staging folder (deploy\staging): app\ and manual\ beneath it.
#   -OutFile        the .msi to write.
#   -SignCertSha1   thumbprint of the code-signing certificate (CurrentUser\My); '' (the default) builds an unsigned MSI.
#   -SignTimestamp  timestamp server.
#
# Written for Windows PowerShell 5.1, which is how the release scripts run.
# =============================================================================

param(
    [Parameter(Mandatory = $true)][ValidatePattern('^\d+\.\d+\.\d+$')][string]$Version,
    [Parameter(Mandatory = $true)][string]$Stage,
    [Parameter(Mandatory = $true)][string]$OutFile,
    [string]$SignCertSha1 = '',
    [string]$SignTimestamp = 'http://timestamp.digicert.com'
)
$ErrorActionPreference = 'Stop'

$Here = $PSScriptRoot
$Root = (Resolve-Path (Join-Path $Here '..')).Path
. (Join-Path $Here 'signing.ps1')

$WixVersion = '6.0.2'   # the same as dotnet-tools.json
$AppDir     = Join-Path $Stage 'app'
$ManualDir  = Join-Path $Stage 'manual'
$Work       = Join-Path $Stage 'msi'
$RunStart   = Get-Date

foreach ($needed in (Join-Path $AppDir 'tmDataQualityAnalyzer.exe'), (Join-Path $AppDir 'settings'), (Join-Path $ManualDir 'UserManual.html')) {
    if (-not (Test-Path -LiteralPath $needed)) { throw "$needed is missing: run deploy\build_package.ps1, which stages it" }
}
if (Test-Path -LiteralPath $Work) { Remove-Item -LiteralPath $Work -Recurse -Force }
New-Item -ItemType Directory -Force -Path $Work | Out-Null

function ConvertTo-XmlAttribute([string]$Text) {
    return [System.Security.SecurityElement]::Escape($Text)
}

# --- settings\: one component a file, never overwritten (NeverOverwrite) and never removed (Permanent). ---
# The operator edits these files (the Receiver SNR defaults, the word maps); neither an upgrade nor an uninstall may take
# the edit away. Files cannot set NeverOverwrite or Permanent, so the fragment is written here.
$script:DirCount  = 0
$script:FileCount = 0
$script:Components = New-Object System.Text.StringBuilder

function Get-SettingsDirectoryXml([string]$Path, [string]$Id, [string]$Name, [int]$Depth) {
    $pad = '  ' * $Depth
    $inner = ''
    foreach ($dir in (Get-ChildItem -LiteralPath $Path -Directory | Sort-Object Name)) {
        $script:DirCount++
        $inner += Get-SettingsDirectoryXml -Path $dir.FullName -Id "SettingsDir$($script:DirCount)" -Name $dir.Name -Depth ($Depth + 1)
    }
    foreach ($file in (Get-ChildItem -LiteralPath $Path -File | Sort-Object Name)) {
        $script:FileCount++
        $fid = "SettingsFile$($script:FileCount)"
        $source = ConvertTo-XmlAttribute $file.FullName
        $null = $script:Components.AppendLine("      <Component Id=`"$fid`" Directory=`"$Id`" NeverOverwrite=`"yes`" Permanent=`"yes`">")
        $null = $script:Components.AppendLine("        <File Id=`"$fid`" Source=`"$source`" KeyPath=`"yes`" />")
        $null = $script:Components.AppendLine('      </Component>')
    }
    return "$pad<Directory Id=`"$Id`" Name=`"$(ConvertTo-XmlAttribute $Name)`">`r`n$inner$pad</Directory>`r`n"
}

$directories = Get-SettingsDirectoryXml -Path (Join-Path $AppDir 'settings') -Id 'SettingsRoot' -Name 'settings' -Depth 3
if ($script:FileCount -eq 0) { throw 'the staged settings folder holds no files' }
$settingsWxs = Join-Path $Work 'Settings.wxs'
$fragment = @"
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by deploy\build_msi.ps1 from the staged settings\ folder. Do not edit. -->
<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">
  <Fragment>
    <DirectoryRef Id="INSTALLFOLDER">
$directories    </DirectoryRef>
  </Fragment>
  <Fragment>
    <ComponentGroup Id="SettingsFiles">
$($script:Components.ToString())    </ComponentGroup>
  </Fragment>
</Wix>
"@
[System.IO.File]::WriteAllText($settingsWxs, $fragment, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "  settings fragment: $($script:FileCount) files in $($script:DirCount + 1) folders"

# --- The licence page wants RTF; the repository's LICENSE is plain text. ---
$licenseRtf = Join-Path $Work 'license.rtf'
$rtf = New-Object System.Text.StringBuilder
$null = $rtf.Append('{\rtf1\ansi\deff0{\fonttbl{\f0\fmodern Courier New;}}\f0\fs18 ')
foreach ($line in ((Get-Content -LiteralPath (Join-Path $Root 'LICENSE') -Raw) -split "`r?`n")) {
    $text = $line.Replace('\', '\\').Replace('{', '\{').Replace('}', '\}')
    $encoded = foreach ($c in $text.ToCharArray()) { if ([int]$c -gt 126) { '\u' + [int]$c + '?' } else { [string]$c } }
    $null = $rtf.Append(($encoded -join '')).Append('\par').AppendLine()
}
$null = $rtf.Append('}')
[System.IO.File]::WriteAllText($licenseRtf, $rtf.ToString(), [System.Text.Encoding]::ASCII)

# --- Build. ---
Push-Location $Root
try {
    & dotnet tool restore --verbosity quiet
    if ($LASTEXITCODE -ne 0) { throw 'dotnet tool restore failed (dotnet-tools.json)' }
    $extensions = (& dotnet tool run wix extension list) | Out-String
    if ($extensions -notmatch 'WixToolset\.UI\.wixext') {
        Write-Host "  adding WixToolset.UI.wixext $WixVersion to the repository's .wix cache"
        & dotnet tool run wix extension add "WixToolset.UI.wixext/$WixVersion"
        if ($LASTEXITCODE -ne 0) { throw 'wix extension add WixToolset.UI.wixext failed' }
    }
    if (Test-Path -LiteralPath $OutFile) { Remove-Item -LiteralPath $OutFile -Force }
    & dotnet tool run wix build -arch x64 -ext WixToolset.UI.wixext -culture en-US `
        -d "AppVersion=$Version" -d "RepoRoot=$Root" -d "StagingApp=$AppDir" -d "StagingManual=$ManualDir" -d "LicenseRtf=$licenseRtf" `
        -intermediatefolder (Join-Path $Work 'obj') -o $OutFile `
        (Join-Path $Here 'tmDataQualityAnalyzer.wxs') $settingsWxs
    if ($LASTEXITCODE -ne 0) { throw 'wix build failed' }
} finally {
    Pop-Location
}

# --- Sign (the exe and DLL inside were signed by build_package.ps1; the package is signed too) and verify. ---
if ($SignCertSha1) {
    Invoke-Signtool -Signtool (Find-Signtool) -Thumbprint $SignCertSha1 -Timestamp $SignTimestamp -File $OutFile
    $signature = Get-AuthenticodeSignature -LiteralPath $OutFile
    if ($signature.Status -ne 'Valid') { throw "the MSI is not validly signed ($($signature.Status))" }
    if ($signature.SignerCertificate.Thumbprint -ne $SignCertSha1) { throw "the MSI is signed, but not by certificate $SignCertSha1" }
    Write-Host '  signed the MSI'
}
if (-not (Test-Path -LiteralPath $OutFile)) { throw 'the MSI was not produced' }
if ((Get-Item -LiteralPath $OutFile).LastWriteTime -lt $RunStart) { throw 'the MSI is left over from an earlier run' }
Write-Host ('  {0}  ({1:N1} MB)' -f $OutFile, ((Get-Item -LiteralPath $OutFile).Length / 1MB))
exit 0
